def build():
    out, seen = [], set()
    for n, c, d in ITEMS:
        if n in seen:
            raise SystemExit(f"同じ品名が2つあります：{n}")
        seen.add(n)
        out.append({"n": n, "c": c, "y": kana.yomi(n), **({"d": d} if d else {})})
    return out


