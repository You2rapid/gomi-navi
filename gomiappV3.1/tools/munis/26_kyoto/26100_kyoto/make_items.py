def zen(s):
    """かっこを全角に"""
    return s.replace("(", "（").replace(")", "）")


def booklet():
    """冊子の「ごみ分別大辞典」→ [品名, 区分, 注意]。区分が2つ以上あるものは、注意の頭に区分を並べる。
    「店頭」（販売店の回収）は、ほかの区分があればそちらをアプリの区分にする"""
    out = []
    for line in BOOKLET.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, codes, note = line.split("|")
        cats = list(dict.fromkeys(CODE[c] for c in codes))
        main = next((c for c in cats if c != "店頭"), "×")
        for a, b in WORDS:
            note = note.replace(a, b)
        note = zen(note)
        if "古" in codes:
            note = "新聞・ダンボール・雑がみは分けて、雑がみの収集日に出せます。コミュニティ回収・古紙回収業者・拠点回収も使えます。"
        elif len(cats) > 1:
            note = "区分：" + "／".join(LABEL[c] for c in cats) + "。" + note
        elif cats == ["店頭"]:
            note = "販売店の回収へ。" + note
        out.append([zen(name), main, note])
    return out


