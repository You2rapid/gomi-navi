def clean(s):
    s = H.unescape(re.sub(r"<[^>]+>", "", re.sub(r"<br\s*/?>", " ", s)))
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", s)).strip().replace("(", "（").replace(")", "）")


def plastics_table(path):
    t = Path(path).read_text(encoding="utf-8")
    out = []
    for tb in re.findall(r"<table.*?</table>", t, re.S):
        if "分別区分" not in tb:
            continue
        for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", tb, re.S):
            cells = [clean(x) for x in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", tr, re.S)]
            if len(cells) >= 3 and cells[-2] in CATS:
                name, kubun, note = cells[-3], cells[-2], cells[-1]
                out.append((CATS[kubun], name.replace(" （", "（"), "" if note in ("-", "－") else note))
    return out


def main():
    m = M.munis(["13111"])[0]
    src = m.src_dir / "出し方"
    rows = plastics_table(src / "plastics_recycle.html")
    if len(rows) < 20:
        raise SystemExit(f"プラスチックのページの表が {len(rows)} 行しか読めません")
    items, seen = [], set()
    for c, n, d in rows + PAGE_ITEMS:
        if n in seen:
            continue
        seen.add(n)
        it = {"n": n, "c": c, "y": kana.yomi(n)}
        if d:
            it["d"] = d
        items.append(it)
    js = [json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in items]
    (m.data_dir / "items.js").write_text(
        f"// 東京都 大田区（13111）の品目検索のデータ（{len(items)}件）\n"
        "// 大田区のページ「プラスチック」の主な分別リストと、「可燃ごみ」「不燃ごみ」「資源（7品目）」「区では収集できないもの」「粗大ごみ」のページの例。"
        "tools/munis/13_tokyo/13111_ota/make_items.py で作る\n"
        "// 1行に1品目：{n:品名, c:区分, y:読み, d:注意}\n"
        'gomiData("13111", "items", /*ITEMS-START*/[\n' + ",\n".join(js) + "\n]/*ITEMS-END*/);\n",
        encoding="utf-8", newline="\n")
    print(f"品目 {len(items)}件（プラスチックの表 {len(rows)}・ページの例 {len(PAGE_ITEMS)}）→ {m.data_dir / 'items.js'}")


if __name__ == "__main__":
    main()
